// Helper function to get suburb by name
export const getSuburbByName = (name) => {
  return melbourneSuburbs.find(suburb => suburb.name === name);
};

// Helper function to get postcode by suburb name
export const getPostcodeByName = (name) => {
  const suburb = getSuburbByName(name);
  return suburb ? suburb.postcode : null;
};

// Helper function to get all suburb names for dropdown
export const getSuburbNames = () => {
  return melbourneSuburbs.map(suburb => suburb.name);
};

